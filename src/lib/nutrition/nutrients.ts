/**
 * Canonical nutrient catalog.
 *
 * Every nutrient the app knows about is defined here exactly once: its unit,
 * category, the USDA FoodData Central nutrient ids it maps to (in priority
 * order), and plain-language educational copy.
 *
 * This module is intentionally framework-free so that build scripts, the
 * estimation engine, the optimizer, and the UI can all share it.
 */

export type NutrientUnit = "kcal" | "g" | "mg" | "µg";

export type NutrientCategory =
  | "energy"
  | "macronutrient"
  | "fat_detail"
  | "vitamin"
  | "mineral"
  | "fatty_acid"
  | "other";

export interface NutrientDef {
  id: NutrientId;
  name: string;
  shortName: string;
  unit: NutrientUnit;
  category: NutrientCategory;
  /** USDA FDC nutrient ids, highest priority first. */
  usdaIds: number[];
  /**
   * When the primary USDA id is missing, a fallback id that is only an
   * approximation of this nutrient (e.g. total 18:3 for ALA). Values taken
   * from a fallback are flagged as approximations.
   */
  usdaApproxIds?: number[];
  /** Shown in the UI's "about this nutrient" panel. */
  role?: string;
  /** Example food sources (general education, not menu claims). */
  sources?: string;
  /** Caveats about how the data or the reference is defined. */
  dataNote?: string;
  /** Digits to show after the decimal point at typical magnitudes. */
  precision: number;
  /** Hidden nutrients are used internally (e.g. water for mass checks). */
  hidden?: boolean;
  /** Included in coverage scoring / completeness views. */
  essential?: boolean;
}

