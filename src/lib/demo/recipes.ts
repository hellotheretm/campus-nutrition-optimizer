/**
 * Recipes for "Demo University", a clearly labelled FICTIONAL campus used for
 * local development, automated tests and validating the estimator.
 *
 * Each recipe is a list of real USDA FoodData Central records with gram
 * weights. From it we derive (a) a ground-truth nutrient profile, (b) an
 * FDA-rounded "official" label, and (c) an ingredient statement in descending
 * order by weight, exactly like a real menu would publish. The estimator only
 * ever sees (b) and (c); comparing its output with (a) measures accuracy.
 *
 * Nothing here describes a real dining hall or menu.
 */

export type DemoPeriod = "breakfast" | "lunch" | "dinner";

export interface DemoIngredient {
  /** Name as printed in the ingredient statement. */
  label: string;
  fdcId: number;
  grams: number;
  /** Sub-ingredients printed in parentheses. */
  sub?: string;
}

export interface DemoRecipe {
  key: string;
  name: string;
  station: string;
  description?: string;
  serving: { amount: number; unit: string };
  /** Cooked weight as a fraction of the raw formulation weight. */
  yield: number;
  /** Publish the gram weight of the serving on the menu (some menus do, some don't). */
  publishGrams: boolean;
  /** Also publish calcium, iron, potassium and vitamin D (newer label style). */
  publishMinerals?: boolean;
  ingredients: DemoIngredient[];
  allergens: string[];
  dietary: string[];
  cooked: boolean;
}

